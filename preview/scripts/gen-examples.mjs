// Generates src/examples/index.ts from manifest.json. Metro needs static imports,
// so the index is a build artifact; `--check` fails if the manifest, the example
// files and the committed index disagree.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'examples');
const manifest = JSON.parse(readFileSync(join(root, 'manifest.json'), 'utf8'));
const check = process.argv.includes('--check');
const problems = [];

const pascal = (s) => s.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const KEBAB = /^[a-z0-9]+(-[a-z0-9]+)*$/;

const imports = [];
const entries = [];
for (const slug of Object.keys(manifest).sort()) {
  if (!KEBAB.test(slug)) problems.push(`slug "${slug}" is not kebab-case`);
  const list = manifest[slug];
  if (!Array.isArray(list) || list.length === 0 || list[0].id !== 'demo') {
    problems.push(`${slug}: the first example must be "demo"`);
    continue;
  }
  const seen = new Set();
  const rows = [];
  for (const { id, title } of list) {
    if (!KEBAB.test(id)) problems.push(`${slug}/${id}: id is not kebab-case`);
    if (seen.has(id)) problems.push(`${slug}/${id}: listed twice`);
    seen.add(id);
    if (!title || title[0] !== title[0].toUpperCase()) problems.push(`${slug}/${id}: title must start with a capital`);
    if (!existsSync(join(root, slug, `${id}.tsx`))) problems.push(`${slug}/${id}: file is missing`);
    const name = pascal(slug) + pascal(id);
    imports.push(`import ${name} from './${slug}/${id}';`);
    rows.push(`    '${id}': ${name},`);
  }
  entries.push(`  '${slug}': {\n${rows.join('\n')}\n  },`);
  const dir = join(root, slug);
  if (existsSync(dir)) {
    for (const f of readdirSync(dir)) {
      if (f.endsWith('.tsx') && !seen.has(f.slice(0, -4))) problems.push(`${slug}/${f}: file is not in the manifest`);
    }
  }
}
for (const d of readdirSync(root, { withFileTypes: true })) {
  if (d.isDirectory() && !(d.name in manifest)) problems.push(`${d.name}/: directory is not in the manifest`);
}

const out = `// Generated by scripts/gen-examples.mjs from manifest.json. Do not edit.
import type { ComponentType } from 'react';

${imports.join('\n')}

export const examples: Record<string, Record<string, ComponentType>> = {
${entries.join('\n')}
};
`;
const indexPath = join(root, 'index.ts');

if (check) {
  if (!existsSync(indexPath) || readFileSync(indexPath, 'utf8') !== out) {
    problems.push('src/examples/index.ts is out of date (run npm run gen:examples)');
  }
} else if (!problems.length) {
  writeFileSync(indexPath, out);
}

if (problems.length) {
  console.error(problems.map((p) => `FAIL ${p}`).join('\n'));
  process.exit(1);
}
console.log(check ? 'check:examples: OK' : `gen:examples: wrote ${Object.keys(manifest).length} components`);
